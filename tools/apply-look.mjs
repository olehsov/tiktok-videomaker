// Generate videos/_template/kit/tokens.css from tokens.base.css + config.json "look" (+ temporary overrides).
// Usage: node tools/apply-look.mjs [--set key=value ...] [--neutral] [--base <file>] [--out <file>] [--json]
//   --set k=v   temporary override (never written to config.json); several allowed
//   --neutral   ignore config.look and use the neutral values (original palette)
//   --json      print the effective look as JSON to stdout (nothing else)
// tokens.base.css is the original and is never modified. Same input → same output. Neutral values → original scene colours.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { ROOT, config, die } from "./lib.mjs";
import { SCENE_TOKENS, adjust, tintHex, shadeHex, dist } from "../videos/_template/kit/color.mjs";

export const KIT = join(ROOT, "videos", "_template", "kit");
/** key: [min, max, neutral] — numeric; enums below. Documented in docs/style-guide.md "Look parameters". */
export const RANGES = {
  saturation: [0, 2, 1], lightness: [0.5, 1.5, 1], maxLightness: [0.5, 1, 0.94], contrast: [0.5, 1.5, 1], temperature: [-1, 1, 0],
  faceShading: [0, 1, 0.5], outline: [0, 6, 0], shadowOpacity: [0, 1, 0], depthFade: [0, 1, 0],
  nightDarkness: [0, 0.8, 0.35], nightBlue: [0, 1, 0.5], uiScale: [0.7, 1.4, 1], captionScale: [0.7, 1.3, 1], captionShadow: [0, 2, 1],
  sharpen: [0, 1.5, 0], crf: [10, 30, 18], grain: [0, 1, 0], vignette: [0, 1, 0],
};
export const TUNES = ["animation", "film", "stillimage", "grain", "none"];
export const NEUTRAL = { ...Object.fromEntries(Object.entries(RANGES).map(([k, v]) => [k, v[2]])), x264Tune: "animation" };

/** Effective look: config.look (or neutral) + overrides, validated and clamped (a clamp prints a warning). */
export function effectiveLook(overrides = {}, { neutral = false } = {}) {
  const base = neutral ? { ...NEUTRAL } : { ...NEUTRAL, ...(config().look || {}) };
  const out = { ...base };
  for (const [k, raw] of Object.entries(overrides)) {
    if (!(k in NEUTRAL)) die(`unknown look key '${k}' (have: ${Object.keys(NEUTRAL).join(", ")})`);
    out[k] = k === "x264Tune" ? String(raw) : Number(raw);
  }
  for (const [k, [lo, hi]] of Object.entries(RANGES)) {
    if (!Number.isFinite(out[k])) die(`look.${k} must be a number`);
    if (out[k] < lo || out[k] > hi) { console.error(`WARN: look.${k}=${out[k]} outside ${lo}…${hi}, clamped`); out[k] = Math.min(hi, Math.max(lo, out[k])); }
  }
  if (!TUNES.includes(out.x264Tune)) die(`look.x264Tune must be one of ${TUNES.join(", ")}`);
  return out;
}

const r = (n, d = 3) => Math.round(n * 10 ** d) / 10 ** d;

/** Pure function: base tokens.css text + look → generated tokens.css text. */
export function generate(baseCss, look) {
  const colorOpts = { saturation: look.saturation, lightness: look.lightness, maxLightness: look.maxLightness, contrast: look.contrast, temperature: look.temperature };
  let css = baseCss;
  const hexOf = {};
  for (const name of SCENE_TOKENS) {
    const re = new RegExp(`(--${name}\\s*:\\s*)(#[0-9A-Fa-f]{6})`);
    const m = css.match(re);
    if (!m) throw new Error(`scene token --${name} (hex) not found in base tokens`);
    hexOf[name] = adjust(m[2], colorOpts);
    css = css.replace(re, `$1${hexOf[name]}`);
  }
  // typography / UI size tokens scaled by uiScale and captionScale
  const scale = (name, k) => { css = css.replace(new RegExp(`(--${name}\\s*:\\s*)(\\d+(?:\\.\\d+)?)px`), (_, a, v) => `${a}${r(v * k, 1)}px`); };
  for (const n of ["plate-size", "callout-title-size", "callout-sub-size", "gauge-size", "meter-size", "label-size"]) scale(n, look.uiScale);
  for (const n of ["caption-size-max", "caption-size-min"]) scale(n, look.captionScale);
  const cs = look.captionShadow;
  css = css.replace(/--text-shadow\s*:[^;]+;/, `--text-shadow: 0 4px 0 rgba(10, 16, 28, ${r(0.55 * cs)}), 0 6px 22px rgba(10, 16, 28, ${r(0.7 * cs)});`);

  // face shading: k = 1 is the original tone spread; tones per scene colour: light / mid / dark
  const k = look.faceShading / 0.5;
  const tones = ["earth-1", "earth-2", "earth-3", "sand", "stone", "snow", "green-dark", "green-mid", "wood", "water"]
    .map((n) => `  --${n}-light: ${tintHex(hexOf[n], 14 * k)};\n  --${n}-mid: ${hexOf[n]};\n  --${n}-dark: ${shadeHex(hexOf[n], 18 * k)};`).join("\n");

  const block = `
/* ===== LOOK — generated by tools/apply-look.mjs from tokens.base.css + config.json "look". Do not edit this file. ===== */
:root {
  --face-k: ${r(k)};              /* faceShading / 0.5: multiplies every shade() / tint() step of the low-poly faces */
  --outline-w: ${r(look.outline, 2)}px;       /* polygon outline width */
  --outline-c: ${shadeHex(hexOf["earth-3"], 40)};
  --shadow-op: ${r(look.shadowOpacity)};         /* ground shadow opacity */
  --depth-fade: ${r(look.depthFade)};         /* far layers blend toward the sky */
  --night-darkness: ${r(look.nightDarkness)};
  --night-blue: ${r(look.nightBlue)};
  --ui-scale: ${r(look.uiScale)};
  --caption-scale: ${r(look.captionScale)};
  --grain: ${r(look.grain)};               /* applied by the finishing step (tools/finish.mjs), not by CSS */
  --vignette: ${r(look.vignette)};            /* idem */
  --sharpen: ${r(look.sharpen)};             /* idem */
${tones}
}
`;
  return css.replace(/\s*$/, "\n") + block;
}

// ---------------------------------------------------------------- CLI
if (import.meta.url === `file://${process.argv[1]}`) {
  const argv = process.argv.slice(2), over = {}; let neutral = false, base = join(KIT, "tokens.base.css"), out = join(KIT, "tokens.css"), json = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--neutral") neutral = true;
    else if (a === "--json") json = true;
    else if (a === "--base") base = resolve(argv[++i]);
    else if (a === "--out") out = resolve(argv[++i]);
    else if (a === "--set" || a.startsWith("--set=")) {
      const kv = a === "--set" ? argv[++i] : a.slice(6);
      const [k, ...v] = (kv ?? "").split("=");
      if (!k || !v.length) die(`--set needs key=value, got '${kv}'`);
      over[k] = v.join("=");
    } else die(`unknown argument ${a}`);
  }
  const look = effectiveLook(over, { neutral });
  if (json) { console.log(JSON.stringify(look, null, 2)); process.exit(0); }
  const css = generate(readFileSync(base, "utf8"), look);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, css);
  const snow = css.match(/--snow\s*:\s*(#[0-9A-F]{6})/)[1];
  const d = Math.round(dist(snow, "#FFFFFF"));
  console.log(`OK ${out} — ${neutral ? "neutral look" : "look"} ${JSON.stringify(Object.fromEntries(Object.entries(look).filter(([k, v]) => v !== NEUTRAL[k])))}`);
  if (d < 14) console.error(`WARN: --snow ${snow} is only ${d} from pure white — snow and white captions/UI will look alike; lower lightness or maxLightness`);
}
